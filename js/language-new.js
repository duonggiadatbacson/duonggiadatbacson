function applyLanguage(lang) {
    const dictionary = translations[lang] || translations.vi;

    document.querySelectorAll("[data-i18n]").forEach(function(element) {
        const key = element.getAttribute("data-i18n");

        if (dictionary[key] !== undefined) {

            /*
             * Trang chủ dùng biểu tượng 🏠.
             * Không thay textContent của nav.home.
             * Chỉ cập nhật aria-label và title.
             */

            if (key === "nav.home") {
                element.setAttribute(
                    "aria-label",
                    dictionary[key]
                );

                element.setAttribute(
                    "title",
                    dictionary[key]
                );

                return;
            }

            element.textContent = dictionary[key];
        }
    });


    document.querySelectorAll("[data-i18n-alt]").forEach(function(element) {
        const key = element.getAttribute("data-i18n-alt");

        if (dictionary[key] !== undefined) {
            element.setAttribute(
                "alt",
                dictionary[key]
            );
        }
    });


    document.documentElement.lang = lang;


    /*
     * SEO cho trang chủ
     */

    if (lang === "en") {

        document.title =
            "Quynh Son Travel | Explore Bac Son, Lang Son";

        const description =
            document.querySelector(
                'meta[name="description"]'
            );

        if (description) {
            description.setAttribute(
                "content",
                "Quynh Son Travel, Bac Son, Lang Son. Discover Tay villages, traditional stilt houses, local culture, cuisine, the Bac Son Valley and unique experiences in Quynh Son."
            );
        }

    } else {

        document.title =
            "Du lịch Quỳnh Sơn | Khám phá Bắc Sơn, Lạng Sơn";

        const description =
            document.querySelector(
                'meta[name="description"]'
            );

        if (description) {
            description.setAttribute(
                "content",
                "Du lịch Quỳnh Sơn, Bắc Sơn, Lạng Sơn. Khám phá làng Tày, nhà sàn truyền thống, văn hóa, ẩm thực địa phương, thung lũng Bắc Sơn và những trải nghiệm đặc sắc tại Quỳnh Sơn."
            );
        }
    }


    /*
     * Cập nhật nút VI / EN
     */

    document.querySelectorAll(
        ".language-switcher button"
    ).forEach(function(button) {

        button.classList.toggle(
            "active",
            button.getAttribute("data-lang") === lang
        );

    });


    localStorage.setItem(
        "language",
        lang
    );
}


function setLanguage(lang) {
    applyLanguage(lang);
}


document.addEventListener("DOMContentLoaded", function() {

    const savedLanguage =
        localStorage.getItem("language") || "vi";


    applyLanguage(savedLanguage);


    document.querySelectorAll(
        ".language-switcher button"
    ).forEach(function(button) {

        button.addEventListener(
            "click",
            function() {

                const lang =
                    button.getAttribute("data-lang");

                applyLanguage(lang);

            }
        );

    });

});