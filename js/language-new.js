function applyLanguage(lang) {
    const dictionary = translations[lang] || translations.vi;

    document.querySelectorAll("[data-i18n]").forEach(function(element) {
        const key = element.getAttribute("data-i18n");

        if (dictionary[key] !== undefined) {
            element.textContent = dictionary[key];
        }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach(function(element) {
        const key = element.getAttribute("data-i18n-alt");

        if (dictionary[key] !== undefined) {
            element.setAttribute("alt", dictionary[key]);
        }
    });

    document.documentElement.lang = lang;

    if (lang === "en") {
        document.title = "Duong Gia Dat Homestay | Quynh Son, Bac Son, Lang Son";
        document.querySelector('meta[name="description"]').setAttribute(
            "content",
            "Duong Gia Dat Homestay in Quynh Son Village, Bac Son, Lang Son. Experience a traditional stilt house, Tay culture, local cuisine and the beauty of Bac Son."
        );
    } else {
        document.title = "Dương Gia Đạt Homestay | Quỳnh Sơn, Bắc Sơn, Lạng Sơn";
        document.querySelector('meta[name="description"]').setAttribute(
            "content",
            "Dương Gia Đạt Homestay tại Làng Quỳnh Sơn, Bắc Sơn, Lạng Sơn. Trải nghiệm nhà sàn truyền thống, văn hóa Tày, ẩm thực địa phương và khám phá vẻ đẹp Bắc Sơn."
        );
    }

    document.querySelectorAll(".language-switcher button").forEach(function(button) {
        button.classList.toggle(
            "active",
            button.getAttribute("data-lang") === lang
        );
    });

    localStorage.setItem("language", lang);
}

function setLanguage(lang) {
    applyLanguage(lang);
}

document.addEventListener("DOMContentLoaded", function() {
    const savedLanguage = localStorage.getItem("language") || "vi";

    applyLanguage(savedLanguage);

    document.querySelectorAll(".language-switcher button").forEach(function(button) {
        button.addEventListener("click", function() {
            const lang = button.getAttribute("data-lang");
            applyLanguage(lang);
        });
    });
});